def main():
    """生成所有历史文章"""
    articles_path = Path(__file__).parent.parent / "articles"
    articles_path.mkdir(exist_ok=True)
    
    current_date = start_date
    day_number = 1
    
    while current_date <= today:
        title, content = generate_article(day_number, current_date)
        
        # 保存文章
        filename = current_date.strftime("%Y-%m-%d") + ".md"
        filepath = articles_path / filename
        
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(content)
        
        print(f"Generated: {filename} - {title}")
        
        current_date += timedelta(days=1)
        day_number += 1
    
    print(f"\nTotal: {day_number - 1} articles generated")

if __name__ == "__main__":
    main()
