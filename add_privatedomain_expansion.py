def get_churn_risk_score(member):
    score = 0
    
    # R（最近入住）评分
    days_since = member['days_since_last_stay']
    if days_since > 365: score += 40
    elif days_since > 180: score += 25
    elif days_since > 90: score += 10
    
    # F（入住频率）评分
    annual_stays = member['annual_stays']
    if annual_stays == 0: score += 20
    elif annual_stays == 1: score += 10
    
    # 互动行为评分
    if member['wechat_read_rate'] < 0.1: score += 15  # 从不看群消息
    if member['coupon_usage_rate'] < 0.2: score += 15   # 券不用
    
    # 其他预警
    if member['complaint_count'] > 0: score += 20
    if member['recent_downgrade']: score += 15
    
    # 风险等级
    if score >= 60: return "高风险"
    elif score >= 30: return "中风险"
    else: return "低风险"
