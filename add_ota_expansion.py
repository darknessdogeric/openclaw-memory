# 携程投放ROI计算
def calculate_ctrip_roi(ad_spend, additional_nights, avg_adrr, commission_rate):
    additional_revenue = additional_nights * avg_adrr
    ctrip_commission = additional_revenue * commission_rate
    net_revenue = additional_revenue - ctrip_commission
    roi = (net_revenue - ad_spend) / ad_spend * 100
    
    return {
        'additional_revenue': additional_revenue,
        'ctrip_commission': ctrip_commission,
        'net_revenue': net_revenue,
        'roi': roi
    }

# 示例
result = calculate_ctrip_roi(
    ad_spend=10000,        # 投放1万元
    additional_nights=150,  # 增加150间夜
    avg_adrr=400,          # 平均房价400
    commission_rate=0.15   # 携程佣金15%
)
print(f"ROI: {result['roi']:.1f}%")  # 约140%
