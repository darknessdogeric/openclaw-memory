def patch(text, label):
    count = 0
    for old, new in REPLACEMENTS:
        n = text.count(old)
        if n:
            text = text.replace(old, new)
            count += n
            print(f'  [{label}] patched "{old[:40]}..." x{n}')
    return text, count

