    ch = text[rng[0]:rng[1]]
    m = re.search(r"^### " + re.escape(sub_head) + r".*$", ch, re.M)
    if not m: return text, False
    s = m.start()
    m2 = re.search(r"^### ", ch[m.end():], re.M)
    e = m.end() + m2.start() if m2 else len(ch)
    return text[:rng[0]] + ch[:s] + new_body.rstrip() + "\n\n" + ch[e:] + text[rng[1]:], True

