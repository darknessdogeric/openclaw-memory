def strip_num(t):
    return re.sub(r"^\(?\d+(\.\d+)?\)?[\.、\uff09]?\s*", "", t).strip()
def strip_cn(t):
    return re.sub(r"^\uff08[^\uff09]+\uff09\s*", "", t).strip()

def emit_block(bl, lvl, num):
    """lvl: 3 -> ###, 4 -> ####; num: 序号或None"""
    t = strip_num(bl["title"])
    t = strip_cn(t)
    head = ("### \uff08%s\uff09%s" % (cn(num), t)) if lvl == 3 else ("#### %d. %s" % (num, t))
    body = "\n".join(bl["body"]).strip("\n")
    return head + "\n\n" + body

def emit_chapter(title, items):
    """items: (chapter, [idxs]) 或 (chapter, [idxs], h3标题) —— 无 h3 标题时每块独立成 ###"""
    out = ["## " + title]
    n = 0
    for item in items:
        c, idxs = item[0], item[1]
        h3t = item[2] if len(item) > 2 else None
        blocks = c["blocks"]
        if not blocks:
            out.append("\n".join(c["raw"]).strip("\n"))
            continue
        if h3t is None:
            for i in idxs:
                n += 1
                out.append(emit_block(blocks[i], 3, n))
        else:
            n += 1
            inner = [emit_block(blocks[i], 4, j) for j, i in enumerate(idxs, 1)]
            out.append("### \uff08%s\uff09%s" % (cn(n), h3t))
            out.append("\n\n".join(inner))
    return "\n\n".join(out)

