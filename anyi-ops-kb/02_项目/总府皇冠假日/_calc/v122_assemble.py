def renum(t, old_n, new_n, new_title=None):
    """把 '## N. xxx' 改为 '## newN. yyy'，并把子章节 '### N.M' 重编"""
    lines = t.split("\n")
    out = []
    for l in lines:
        if l.startswith("## "):
            rest = l[3:]
            num, _, title = rest.partition(". ")
            if new_title: title = new_title
            l = "## %d. %s" % (new_n, title)
        elif l.startswith("### "):
            rest = l[4:]
            num, _, title = rest.partition(" ")
            # 子编号重编：'N.M xxx' -> 'newN.M xxx'
            m = re.match(r"(\d+)\.(\d+)\s*(.*)", title)
            if m: l = "### %d.%s %s" % (new_n, m.group(2), m.group(3))
        out.append(l)
    return "\n".join(out)

