def build(key, brand, pub_mode, room_mode, months, preopen, cont, feas):
    to32 = (room_mode == "3改2")
    n_rooms = 268 if to32 else 402
    # ── 段一：停业损失 ──
    loss = LOSS_PER_MONTH * months
    # ── 段二：机电水电强弱电及隐蔽工程 ──
    mep_items = mep_block(to32)
    mep_total = sum(v for _, v, _ in mep_items)
    # ── 段三 A：客房改造 ──
    rrate = ROOM_KEEP[brand] if pub_mode == "保留" else ROOM_REBUILD[brand]
    if to32:
        # 3 改 2 后按 48 ㎡/间，含移卫，故按重做单价另加保留项扣减
        per_room = sum(v for _, v in rrate) * ROOM_AREA_32 / 10000.0
        if pub_mode == "保留":
            per_room = (sum(v for _, v in rrate) * ROOM_AREA_32 / 10000.0) * 0.72   # 移卫后仍可保留部分主材
    else:
        per_room = sum(v for _, v in rrate) * ROOM_AREA_KEEP / 10000.0
    room_total = per_room * n_rooms
    # ── 段三 B：公共区域 ──
    pub_total = 0.0
    pub_rows = []
    for nm, a in AB.PUBLIC_AREA.items():
        r = PUBLIC_RATE[pub_mode][brand][nm]
        w = a * r / 10000.0
        pub_rows.append((nm, a, r, round(w, 1)))
        pub_total += w
    # ── 段三 C：后场（在公区内单列，此处为其中装修部分，已含在 pub_total 的后场工区项）──
    # ── 段三 D：拆除（随做法变）──
    demolish = 300 if pub_mode == "保留" else 520
    # ── 段三 E：艺术品与在地策展（仅奢牌）──
    art = 0.0
    if brand == "外部奢牌": art = 1250
    elif brand == "洲至奢选": art = 380
    # ── 不可预见费 ──
    direct = room_total + pub_total + demolish + art + preopen
    unexp = direct * cont
    fitout = room_total + pub_total + demolish + art + preopen + unexp
    total = loss + mep_total + fitout
    return dict(key=key, brand=brand, pub_mode=pub_mode, room_mode=room_mode, months=months,
                feas=feas, n_rooms=n_rooms, loss=round(loss, 1), mep=round(mep_total, 1),
                mep_items=mep_items, per_room=round(per_room, 2), room_total=round(room_total, 1),
                pub_rows=pub_rows, pub_total=round(pub_total, 1), demolish=demolish, art=art,
                preopen=preopen, unexp=round(unexp, 1), fitout=round(fitout, 1),
                total=round(total, 1), per_key_fitout=round(fitout / n_rooms, 2),
                per_key_total=round(total / n_rooms, 2))

RES = []
for d in DIRS:
    r = build(*d)
