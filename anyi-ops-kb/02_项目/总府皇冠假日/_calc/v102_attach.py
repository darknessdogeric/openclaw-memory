def mk(styles=True):
    d = Document()
    if styles:
        st = d.styles["Normal"]; st.font.name = FS; st.font.size = Pt(11)
        st.element.rPr.rFonts.set(qn("w:eastAsia"), FS)
    for s in d.sections:
        s.page_width, s.page_height = Cm(21.0), Cm(29.7)
        s.top_margin, s.bottom_margin = Cm(3.0), Cm(2.8)
        s.left_margin, s.right_margin = Cm(2.8), Cm(2.6)
    return d

def H(d, t, lvl=1, size=16, align="center", before=10, after=8):
    p = d.add_paragraph(); p.alignment = {"center": WD_ALIGN_PARAGRAPH.CENTER,
        "left": WD_ALIGN_PARAGRAPH.LEFT}[align]
    pf = p.paragraph_format; pf.space_before = Pt(before); pf.space_after = Pt(after)
    pf.line_spacing = Pt(size + 8)
    r = p.add_run(t); r.font.size = Pt(size); r.bold = (lvl >= 2)
    r.font.name = HT if lvl >= 2 else BT
    r._element.rPr.rFonts.set(qn("w:eastAsia"), HT if lvl >= 2 else BT)
    return p

def P(d, t, indent=True, size=11, bold=False, after=2, align="justify"):
    p = d.add_paragraph(); p.alignment = {"justify": WD_ALIGN_PARAGRAPH.JUSTIFY,
        "left": WD_ALIGN_PARAGRAPH.LEFT, "center": WD_ALIGN_PARAGRAPH.CENTER}[align]
    pf = p.paragraph_format; pf.space_after = Pt(after); pf.line_spacing = Pt(size + 6)
    if indent: pf.first_line_indent = Pt(size * 2)
    r = p.add_run(t); r.font.size = Pt(size); r.bold = bold
    r.font.name = FS; r._element.rPr.rFonts.set(qn("w:eastAsia"), FS)
    return p

def TBL(d, headers, rows, fs=9):
    t = d.add_table(rows=1, cols=len(headers)); t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(headers):
        c = t.rows[0].cells[j]; c.text = ""
        p = c.paragraphs[0]; p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(str(h)); r.font.size = Pt(fs); r.bold = True; r.font.name = HT
        r._element.rPr.rFonts.set(qn("w:eastAsia"), HT)
    for row in rows:
        cells = t.add_row().cells
        for j, v in enumerate(row):
            cells[j].text = ""
            p = cells[j].paragraphs[0]; p.paragraph_format.space_after = Pt(0)
            p.paragraph_format.line_spacing = Pt(fs + 3)
            r = p.add_run(str(v)); r.font.size = Pt(fs); r.font.name = FS
            r._element.rPr.rFonts.set(qn("w:eastAsia"), FS)
    return t

def footer_pg(d):
    for s in d.sections:
        p = s.footer.paragraphs[0]; p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(); r.font.size = Pt(9)
        for el, attr in (("w:fldChar", ("w:fldCharType", "begin")), ("w:instrText", None), ("w:fldChar", ("w:fldCharType", "end"))):
            e = r._element.makeelement(qn(el), {})
            if el == "w:instrText":
                e.set(qn("xml:space"), "preserve"); e.text = "PAGE"
            else:
                e.set(qn(attr[0]), attr[1])
            r._element.append(e)

