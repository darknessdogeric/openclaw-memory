def seg3(b, m, cfg):
    # 自营品牌在 039 造价表无独立锚点：物理装修标准与「皇冠」同级，仅品牌专项构成不同，
    # 故按「皇冠」实体锚点代理（代理关系已在报告口径说明中列明）
    bb = '皇冠' if b=='自营' else b
    c = CFG[cfg]; key=(bb,m,cfg)
    if key in A39:
        ar,aa,av = A39[key]
        s3 = av + (c['rm']*c['ab'] - ar*aa)*UNIT[(bb,m)]/1e4
    else:
        cand=[(k,v) for k,v in A39.items() if k[0]==bb and k[1]==m] or [(k,v) for k,v in A39.items() if k[0]==bb]
        _, vv = max(cand, key=lambda kv: kv[1][0]); ar,aa,av=vv
        s3 = c['rm']*c['ab']*UNIT[(bb,m)]/1e4 + (av - ar*aa*UNIT[(bb,m)]/1e4)
    sp = SP_SELF if b=='自营' else SP_IHG
    return round(s3 + sp, 1)
def arm_cash(p, adr, occ, capex=None, du=None):
    du = p['du']; F=p['fees']; cfs=[]
    capex = p['cap'] if capex is None else capex
    capm = capex/du
    for m in range(1, du+1): cfs.append((m, -capm - RIGID_M))
    for y in range(1, OP_Y+1):
        af, of = factors(y)
        room = p['rm']*365*occ*adr*af/1e4
        nonroom = (M['nonroom_base']*(occ/M['occ_now'])*(1+M['nonroom_link']*(adr/M['adr_now']-1)))
        R = room+nonroom; goi = R*M['goi_rate']
        scale = (p['rm']/402.0)**0.35
        var = M['var_rate'] - M['energy_rate']*(1-M['energy_new']) - M['pom_rate']*(1-M['pom_new'])
        unalloc = M['fixed_agit']*scale + R*var + R*F['uplift']
        adj_gop = goi - unalloc - R*F['lic']
        fee_inc = max(0.0, adj_gop)*F['inc']; fee_other = R*F['ffe']
        cf = adj_gop - fee_inc - fee_other
        for k in range(12): cfs.append((du+(y-1)*12+k+1, cf/12.0))
    return cfs
def npv(cfs, r=RA):
    rm=(1+r)**(1/12.0)-1
    return sum(v/((1+rm)**m) for m,v in cfs)
def irr(cfs):
    lo,hi=-0.95,5.0
    def g(r):
        rm=(1+r)**(1/12.0)-1
        return sum(v/((1+rm)**m) for m,v in cfs)
    if g(lo)*g(hi)>0: return None
    for _ in range(200):
        mid=(lo+hi)/2
        if g(lo)*g(mid)<=0: hi=mid
        else: lo=mid
    return (lo+hi)/2
def payback(cfs):
    cum=0.0
    for m,v in cfs:
        cum+=v
        if cum>=0 and m>0: return m/12.0
    return None
def bisect(fn, lo, hi, n=60, rev=False):
    flo,fhi=fn(lo),fn(hi)
    if flo*fhi>0: return None
    for _ in range(n):
        mid=(lo+hi)/2.0; pos=fn(mid)>0
        if rev:
            if pos: lo=mid
            else: hi=mid
        else:
            if pos: hi=mid
            else: lo=mid
    return (lo+hi)/2.0

