def set_cell_bg(cell, color_hex):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), color_hex)
    tc_pr.append(shd)


def set_cell_text(cell, text, font='微软雅黑', size=8, bold=False, color=None,
                  align=WD_ALIGN_PARAGRAPH.LEFT):
    cell.text = ''
    p = cell.paragraphs[0]
    p.alignment = align
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(0)
    p.paragraph_format.line_spacing = 1.1
    run = p.add_run(text)
    run.font.name = font
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor.from_string(color)
    rpr = run._element.get_or_add_rPr()
    rfonts = OxmlElement('w:rFonts')
    rfonts.set(qn('w:eastAsia'), font)
    rfonts.set(qn('w:ascii'), font)
    rfonts.set(qn('w:hAnsi'), font)
    rpr.insert(0, rfonts)
    cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER


def grade_color(grade):
    return {'S': 'C8102E', 'A': '1F4D2A', 'B': 'B7791F', 'C': '707070', 'D': '999999'}.get(grade, '000000')


def mbi_color(mbi):
    if mbi >= 90: return 'C8102E'
    if mbi >= 80: return '1F4D2A'
    if mbi >= 70: return 'B7791F'
    return '707070'


