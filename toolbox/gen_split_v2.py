def build_l1_file(filename, title, subtitle, dim_blocks):
    """dim_blocks: list of (h3_title, [table_headers, table_rows])"""
    try:
        doc, _ = new_doc()
        T1(doc, title)
        T2(doc, subtitle)
        P(doc, '')
        P(doc, '维护者：B166ER（产业发展部）')
        P(doc, '创建日期：2026-08-29')
        P(doc, '')
        for h3_title, headers, rows in dim_blocks:
            T3(doc, h3_title)
            add_table(doc, headers, rows)
            P(doc, '')
        save(doc, os.path.join(DIR1, filename))
    except Exception as e:
        print(f'[FAIL] {filename}: {e}')
        traceback.print_exc()

