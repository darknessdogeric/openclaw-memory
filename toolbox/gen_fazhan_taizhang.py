    for c, v in enumerate(vals, start=1):
        cell = ws.cell(row=r, column=c)
        cell.value = v
        cell._style = copy(styles[c - 1])
        al = copy(cell.alignment)
        al.wrap_text = True
        al.vertical = 'top'
        cell.alignment = al
    if row_h:
        ws.row_dimensions[r].height = row_h

