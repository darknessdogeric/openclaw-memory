def shade(cell, hexc):
    tcPr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement('w:shd'); sh.set(qn('w:val'), 'clear'); sh.set(qn('w:fill'), hexc)
    tcPr.append(sh)


def tbl(headers, rows, widths=None, fs=9, fill='1F3864'):
    t = doc.add_table(rows=1, cols=len(headers)); t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hc = t.rows[0].cells
    for i, htxt in enumerate(headers):
        hc[i].text = ''; pp = hc[i].paragraphs[0]; pp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        F(pp.add_run(htxt), '仿宋_GB2312', fs, True, RGBColor(0xFF, 0xFF, 0xFF)); shade(hc[i], fill)
    for ri, row in enumerate(rows):
        cs = t.add_row().cells
        for ci, val in enumerate(row):
            cs[ci].text = ''; pp = cs[ci].paragraphs[0]; pp.paragraph_format.space_after = Pt(1)
            txt = str(val); bold = txt.startswith('**')
            F(pp.add_run(txt.replace('**', '')), '仿宋_GB2312', fs, bold)
            if ri % 2 == 1:
                shade(cs[ci], 'F2F5FA')
    if widths:
        for r in t.rows:
            for i, w in enumerate(widths):
                r.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


