TIER = {  # (机型, 购销价, 年服务费模式价, 年服务费)
    "MG200": ("MG200", 10000, 5000, 1500),
    "1510": ("YunGW 1510", 19800, 10000, 3000),
    "1560": ("YunGW 1560", 29800, 15000, 4500),
    "2200": ("YunGW 2200", 59800, 30000, 9000),
}


def tier_of(rooms):
    if rooms is None:
        return "MG200"
    if rooms <= 100:
        return "MG200"
    if rooms <= 200:
        return "1510"
    if rooms <= 350:
        return "1560"
    return "2200"


def calc(hotels):
    """返回 (台数, 购销一次性总价, 第二年起年服务费, 年服务费模式三年总价)"""
    n = 0; buy = 0; svc = 0; yr3 = 0
    for name, rooms, st in hotels:
        t = tier_of(rooms)
        _, b, y, s = TIER[t]
        n += 1; buy += b; svc += s; yr3 += y * 3
    return n, buy, svc, yr3


