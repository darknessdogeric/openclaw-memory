def H(text, level=1, center=False):
    h = doc.add_heading(text, level=level)
    if center: h.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for r in h.runs:
        r.font.name = '宋体'
        r._element.rPr.rFonts.set('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}eastAsia', '宋体')
    return h

def P(text='', bold=False, center=False, indent=False):
    p = doc.add_paragraph()
    if text:
        run = p.add_run(text)
        if bold: run.bold = True
        run.font.name = '宋体'
        run._element.rPr.rFonts.set('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}eastAsia', '宋体')
    if center: p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    if indent: p.paragraph_format.left_indent = Cm(0.74)
    return p

def B(text): return P('· ' + text, indent=True)

def T(headers, rows):
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = 'Light Grid Accent 1'
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = ''
        para = cell.paragraphs[0]
        run = para.add_run(h)
        run.bold = True
        run.font.name = '宋体'
        run._element.rPr.rFonts.set('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}eastAsia', '宋体')
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for row_data in rows:
        row = table.add_row()
        for i, cell_text in enumerate(row_data):
            cell = row.cells[i]
            cell.text = ''
            para = cell.paragraphs[0]
            run = para.add_run(str(cell_text))
            run.font.name = '宋体'
            run._element.rPr.rFonts.set('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}eastAsia', '宋体')
    return table

