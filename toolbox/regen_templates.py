# 通用 7 列模板
def md_table(items, header=None):
    """生成统一 7 列格式的 Markdown 表格"""
    if header is None:
        header = [
            '#', '调研项', '数据来源', '输出形式',
            '安逸集团有无', '现有程度', '备注'
        ]
    lines = ['| ' + ' | '.join(header) + ' |']
    lines.append('|---|--------|---------|---------|---------|------|------|')
    for row in items:
        lines.append('| ' + ' | '.join(str(x) for x in row) + ' |')
    return '\n'.join(lines)


def make_dimension_table(dimension_name, items):
    """生成一整个维度"""
    return f"\n### {dimension_name}\n\n{md_table(items)}\n"


