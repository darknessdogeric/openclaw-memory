def md_table(rows, header=None):
    if header is None:
        header = ['#', '调研项', '数据来源', '输出形式', '安逸集团有无', '现有程度', '备注']
    lines = ['| ' + ' | '.join(header) + ' |']
    lines.append('|---|--------|---------|---------|---------|------|------|')
    for row in rows:
        lines.append('| ' + ' | '.join(str(x) for x in row) + ' |')
    return '\n'.join(lines)


def section(title, rows):
    return f"\n## {title}\n\n{md_table(rows)}\n"


