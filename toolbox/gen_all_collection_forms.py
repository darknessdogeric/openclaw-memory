# 字体工具
def set_run_font(run, font_eastasia, font_name_ascii='Times New Roman', size_pt=18, bold=False):
    run.font.name = font_name_ascii
    run.font.size = Pt(size_pt)
    run.font.bold = bold
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}rFonts')
    if rfonts is None:
        rfonts = OxmlElement('w:rFonts')
        rpr.append(rfonts)
    rfonts.set('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}eastAsia', font_eastasia)
    rfonts.set('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}ascii', font_name_ascii)
    rfonts.set('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}hAnsi', font_name_ascii)

def T1(doc, text):
    p = doc.add_paragraph()
    run = p.add_run(text)
    set_run_font(run, '方正小标宋简体', size_pt=22, bold=True)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER

def T2(doc, text):
    p = doc.add_paragraph()
    run = p.add_run(text)
    set_run_font(run, '黑体', size_pt=16, bold=True)

def P(doc, text='', bold=False, center=False, indent=False):
    p = doc.add_paragraph()
    if text:
        run = p.add_run(text)
        set_run_font(run, '仿宋_GB2312', size_pt=18, bold=bold)
    if center: p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    if indent: p.paragraph_format.first_line_indent = Cm(0.74)

def add_table(doc, headers, rows, header_size=14, body_size=14):
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = 'Light Grid Accent 1'
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = ''
        para = cell.paragraphs[0]
        run = para.add_run(h)
        set_run_font(run, '黑体', size_pt=header_size, bold=True)
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for row_data in rows:
        row = table.add_row()
        for i, ct in enumerate(row_data):
            cell = row.cells[i]
            cell.text = ''
            para = cell.paragraphs[0]
            run = para.add_run(str(ct))
            set_run_font(run, '仿宋_GB2312', size_pt=body_size)
    return table

def new_doc():
    tmp = os.path.join(os.environ['TEMP'], f'_form_{os.getpid()}.docx')
    if os.path.exists(tmp): os.remove(tmp)
    shutil.copyfile(TEMPLATE, tmp)
    doc = Document(tmp)
    body = doc.element.body
    sectPrs = body.findall('.//{http://schemas.openxmlformats.org/wordprocessingml/2006/main}sectPr')
    for child in list(body):
        if child.tag.endswith('}sectPr'): continue
        body.remove(child)
    for sp in sectPrs: body.append(sp)
    return doc

# 通用生成器
def build_form(file_path, title, subtitle, recipient_label,
               data_deadline, submit_deadline, basic_fields, blocks,
               submit_target='集团 OA 系统 → 产业发展部 → 蒋抒伶 / B166ER'):
    doc = new_doc()
    T1(doc, title)
    T2(doc, subtitle)
    P(doc, '')
    P(doc, '编制：B166ER（产业发展部）', center=True)
    P(doc, f'版本：v1.0 · 2026-08-29', center=True)
    P(doc, '')
    # 一、填写说明
    T2(doc, '一、填写说明')
    P(doc, f'1. 本表由【{recipient_label}】填写，相关部门负责人审核签字后提交。')
    P(doc, f'2. 数据截止日期：**{data_deadline}**。')
    P(doc, f'3. 提交截止日期：**{submit_deadline}**。')
    P(doc, f'4. 提交方式：{submit_target}。')
    P(doc, '5. 标注 * 为必填项；标注 ○ 为选填项；标注 ☐ 为单选/多选框，请打勾。')
    P(doc, '6. 数字格式：粉丝/阅读量用阿拉伯数字+万/千；比率用百分比；金额用元为单位。')
    P(doc, '')
    P(doc, '保密声明：', bold=True)
    P(doc, '本表所填数据仅用于集团内部立项决策，集团对所有数据严格保密——不公开、不对外披露、不用于外部用途。')
    P(doc, '')
    # 二、基础信息
    T2(doc, '二、基础信息')
    add_table(doc, ['序号 *', '字段 *', '填写说明', '填写内容'], basic_fields)
    P(doc, '')
    # 三、核心字段
    for block in blocks:
        T2(doc, block['title'])
        if 'note' in block:
            P(doc, block['note'])
        add_table(doc, ['序号 *', '字段 *', '填写说明', '填写内容'], block['fields'])
        P(doc, '')
    # 四、签字确认
    T2(doc, '四、签字确认')
    P(doc, '本表所填数据真实有效，授权集团产业发展部在立项决策范围内使用。')
    P(doc, '')
    add_table(doc, ['岗位 *', '姓名 *', '签字 / 盖章 *', '日期 *'],
        [
            ['填报人', '', '', ''],
            ['部门 / 酒店负责人', '', '', ''],
            ['集团产业发展部接收人', '', '', ''],
        ])
    P(doc, '')
    P(doc, '—— 本表结束 ——', center=True)
    doc.save(file_path)
    print(f'[OK] {os.path.basename(file_path)} ({os.path.getsize(file_path)/1024:.1f} KB)')

