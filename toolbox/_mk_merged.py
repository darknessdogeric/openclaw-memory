for ln in lines:
    ln = ln.rstrip()
    if not ln.strip():
        continue
    body = ln[1:] if ln.startswith('^') else ln
    m = TAG_RE.match(body)
    if m:
        tag, rest = m.group(1), m.group(2)
    else:
        tag, rest = 'N', body
    if tag == 'T':
        add(rest, font=FONT_TITLE, size=22, align=WD_ALIGN_PARAGRAPH.CENTER, indent=False)
    elif tag == 'H':
        add(rest, font=FONT_H, size=16, bold=True, sb=SB1)
    elif tag == 'H2':
        add(rest, font=FONT_H2, size=16, bold=True, sb=SB1)
    elif tag == 'B':
        add(rest)
    elif tag in ('N', 'NB'):
        add(rest, indent=False)
    elif tag == 'P':
        d.add_paragraph()
    else:
        add(rest, indent=False)

