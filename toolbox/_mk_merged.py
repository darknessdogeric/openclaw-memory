def deliver(src, dest):
    try:
        shutil.copy2(src, dest)
        return dest, 'primary'
    except PermissionError:
        base, ext = os.path.splitext(dest)
        alt = base + '_修订版' + ext
        shutil.copy2(src, alt)
        return alt, 'locked->alt'


