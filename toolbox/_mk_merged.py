def add(text, font=FONT_BODY, size=16, bold=False, align=None, indent=True, sb=None):
    p = d.add_paragraph()
    pf = p.paragraph_format
    if align is not None:
        p.alignment = align
    if indent:
        pf.first_line_indent = IND
    if sb is not None:
        pf.space_before = sb
    pf.line_spacing = 1.5
    r = p.add_run(text)
    setfont(r, font, size, bold)
    return p


