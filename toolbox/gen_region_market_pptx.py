def blank(p): return p.slides.add_slide(p.slide_layouts[6])
def rect(s,x,y,w,h,fill,line=None):
    sh=s.shapes.add_shape(MSO_SHAPE.RECTANGLE,Inches(x),Inches(y),Inches(w),Inches(h))
    sh.fill.solid(); sh.fill.fore_color.rgb=fill
    if line is None: sh.line.fill.background()
    else: sh.line.color.rgb=line; sh.line.width=Pt(0.75)
    sh.shadow.inherit=False; return sh
def tb(s,x,y,w,h,text,size=12,bold=False,color=INK,align=PP_ALIGN.LEFT,anchor=MSO_ANCHOR.TOP):
    b=s.shapes.add_textbox(Inches(x),Inches(y),Inches(w),Inches(h)); tf=b.text_frame; tf.word_wrap=True
    tf.margin_left=tf.margin_right=tf.margin_top=tf.margin_bottom=0; tf.vertical_anchor=anchor
    p=tf.paragraphs[0]; p.alignment=align
    r=p.add_run(); r.text=text
    r.font.size=Pt(size); r.font.bold=bold; r.font.color.rgb=color; r.font.name=FONT
    return b
def page(prs,tag,title,idx,total,note=None):
    s=blank(prs); rect(s,0,0,SW,0.52,NAVY)
    tb(s,0.42,0.11,8.5,0.3,tag,11.5,True,WHITE)
    tb(s,10.4,0.11,2.5,0.3,'%02d / %d'%(idx,total),10.5,False,RGBColor(0xC9,0xD6,0xE8),PP_ALIGN.RIGHT)
