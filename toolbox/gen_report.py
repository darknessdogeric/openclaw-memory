def F(run, name='等线', size=10.5, bold=False, color=None):
    run.font.name = name; run.font.size = Pt(size); run.bold = bold
    run._element.rPr.rFonts.set(qn('w:eastAsia'), name)
    if color is not None:
        run.font.color.rgb = color

def title(t, size=17):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    F(p.add_run(t), '等线', size, True); p.paragraph_format.space_after = Pt(3)

def sub(t):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    F(p.add_run(t), '等线', 10, False, GREY); p.paragraph_format.space_after = Pt(12)

def h1(t):
    p = doc.add_paragraph()
    F(p.add_run(t), '等线', 13.5, True, NAVY)
    p.paragraph_format.space_before = Pt(15); p.paragraph_format.space_after = Pt(6)

def h2(t):
    p = doc.add_paragraph()
    F(p.add_run(t), '等线', 11.5, True, BLUE)
    p.paragraph_format.space_before = Pt(10); p.paragraph_format.space_after = Pt(4)

def para(t, bold=False, size=10.5, indent=True, color=None):
    p = doc.add_paragraph()
    F(p.add_run(t), '等线', size, bold, color)
    if indent:
        p.paragraph_format.first_line_indent = Pt(21)
    p.paragraph_format.space_after = Pt(3)

def bl(t, lv=0):
    p = doc.add_paragraph()
    F(p.add_run(('　' * lv) + '· ' + t), '等线', 10.5)
    p.paragraph_format.left_indent = Pt(21 + lv * 13)
    p.paragraph_format.space_after = Pt(2)

def shade(cell, hexc):
    tcPr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement('w:shd'); sh.set(qn('w:val'), 'clear'); sh.set(qn('w:fill'), hexc)
    tcPr.append(sh)

def tbl(headers, rows, widths=None, fill='1F3864', fs=9.5, zebra=True):
    t = doc.add_table(rows=1, cols=len(headers)); t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hc = t.rows[0].cells
    for i, htxt in enumerate(headers):
        hc[i].text = ''; p = hc[i].paragraphs[0]; p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        F(p.add_run(htxt), '等线', fs, True, RGBColor(0xFF, 0xFF, 0xFF)); shade(hc[i], fill)
    for ri, row in enumerate(rows):
        cs = t.add_row().cells
        for ci, val in enumerate(row):
            cs[ci].text = ''; p = cs[ci].paragraphs[0]
            p.paragraph_format.space_after = Pt(1)
            txt = str(val); bold = txt.startswith('**')
            F(p.add_run(txt.replace('**', '')), '等线', fs, bold)
            if zebra and ri % 2 == 1:
                shade(cs[ci], 'F2F5FA')
    if widths:
        for r in t.rows:
            for i, w in enumerate(widths):
                r.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t

