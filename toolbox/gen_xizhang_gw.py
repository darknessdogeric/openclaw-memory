def F(run, name='仿宋_GB2312', size=16, bold=False, color=None):
    run.font.name = name
    run.font.size = Pt(size)
    run.bold = bold
    run._element.rPr.rFonts.set(qn('w:eastAsia'), name)
    if color is not None:
        run.font.color.rgb = color


def p(text, font='仿宋_GB2312', size=16, bold=False, indent_chars=0, align=None,
      first_indent=None, before=0, after=0, spacing=30):
    par = doc.add_paragraph()
    par.paragraph_format.line_spacing_rule = WD_LINE_SPACING.EXACTLY
    par.paragraph_format.line_spacing = Pt(spacing)
    par.paragraph_format.space_before = Pt(before)
    par.paragraph_format.space_after = Pt(after)
    if align is not None:
        par.alignment = align
    if first_indent is not None:
        par.paragraph_format.first_line_indent = Pt(first_indent)
    elif indent_chars:
        par.paragraph_format.first_line_indent = Pt(size * indent_chars)
    F(par.add_run(text), font, size, bold)
    return par


def h1(text):
    """一级标题：黑体三号，顶格，段前段后各 0.5 行"""
