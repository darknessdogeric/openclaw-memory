    try:
        # 尝试从OTA获取
        return ota_api.get_inventory()
    except OTAApiError:
        # 降级：使用PMS本地缓存
        return pms_cache.get_inventory()
    finally:
        # 记录异常，供后续分析
        log_api_failure('ota', 'inventory')
